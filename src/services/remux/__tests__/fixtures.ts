/**
 * A real DASH rendition, small enough to inline: one second of 64×64 VP9 video
 * and one second of mono AAC audio, each as its own single-track fragmented
 * MP4 — the same shape Instagram serves. Generated with ffmpeg's DASH muxer:
 *
 *   ffmpeg -f lavfi -i testsrc2=size=64x64:rate=10 -f lavfi -i sine=frequency=440:sample_rate=22050 \
 *     -t 1 -map 0:v -c:v libvpx-vp9 -b:v 40k -g 5 -map 1:a -c:a aac -b:a 24k -ac 1 \
 *     -map_metadata -1 -fflags +bitexact -flags:v +bitexact -flags:a +bitexact \
 *     -f dash -dash_segment_type mp4 -single_file 1 -seg_duration 0.5 tiny.mpd
 *
 * Two traits make it a useful fixture: the video is split across two
 * fragments with a keyframe every five frames, and the audio carries the
 * open-ended "segment duration 0, media time 1024" priming edit that
 * fragmented audio streams use.
 */

function decode(lines: string[]): Uint8Array<ArrayBuffer> {
  return Uint8Array.from(atob(lines.join("")), (char) => char.charCodeAt(0));
}

